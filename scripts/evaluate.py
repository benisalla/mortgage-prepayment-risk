"""Evaluate the saved models: metrics tables, model figures and permutation importance.

    python scripts/evaluate.py                 # reads models/*.joblib written by train.py

Writes reports/metrics.json, reports/results.md, reports/importance_<task>.csv and the model
figures in reports/figures/ (ROC/PR, confusion matrices, calibration, importance, before/after).
"""
import argparse
import json
from pathlib import Path

import joblib
import pandas as pd

from mbs_risk import config, plotting
from mbs_risk.evaluation import permutation_importance_table

COLS = ["roc_auc", "pr_auc", "f1", "precision", "recall", "threshold", "brier", "accuracy",
        "cv_roc_auc_mean", "cv_roc_auc_std", "fit_seconds"]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models-dir", default=str(config.MODELS_DIR))
    ap.add_argument("--reports", default=str(config.REPORTS_DIR))
    ap.add_argument("--tasks", nargs="+", default=[config.DELINQ_TARGET, config.PREPAY_TARGET])
    args = ap.parse_args()
    rep = Path(args.reports)
    fig = rep / "figures"
    fig.mkdir(parents=True, exist_ok=True)

    summary, md = {}, ["# Results (generated by scripts/evaluate.py)\n"]
    for task in args.tasks:
        res = joblib.load(Path(args.models_dir) / f"{task}.joblib")
        best = res.best_model()
        baseline = "logreg" if "logreg" in res.metrics.index else "majority"
        print(f"[{task}] best={best} baseline={baseline}")

        plotting.plot_roc_pr(res, fig / f"roc_pr_{task}.png")
        plotting.plot_confusions(res, path=fig / f"confusion_{task}.png")
        plotting.plot_calibration(res, fig / f"calibration_{task}.png")
        plotting.plot_before_after(res, baseline, best, fig / f"before_after_{task}.png")

        imp = permutation_importance_table(res.models[best], res.X_test, res.y_test)
        imp.to_csv(rep / f"importance_{task}.csv", index=False)
        plotting.plot_importance(imp, f"Permutation importance: {plotting.NICE[best]} on {task}",
                                 fig / f"importance_{task}.png")

        m = res.metrics[[c for c in COLS if c in res.metrics]].copy()
        summary[task] = {"best_model": best, "n_test": int(len(res.y_test)),
                         "prevalence": float(res.y_test.mean()),
                         "models": json.loads(m.to_json(orient="index")),
                         "top_features": imp.head(10).to_dict(orient="records")}
        md += [f"## {plotting.NICE[task]}\n",
               f"Test set: {len(res.y_test):,} loans, positive rate {res.y_test.mean():.1%}. "
               f"Best model by ROC-AUC: **{best}**.\n",
               m.round(4).to_markdown() if _has_tabulate() else m.round(4).to_string(), "\n",
               "Top permutation importances (drop in ROC-AUC):\n",
               imp.head(10).round(4).to_markdown(index=False) if _has_tabulate() else imp.head(10).round(4).to_string(index=False),
               "\n"]
        print(m.round(4).to_string(), "\n", imp.head(8).round(4).to_string(index=False), "\n")

    (rep / "metrics.json").write_text(json.dumps(summary, indent=2))
    (rep / "results.md").write_text("\n".join(md))
    print(f"wrote {rep / 'metrics.json'} and {rep / 'results.md'}")


def _has_tabulate() -> bool:
    try:
        import tabulate  # noqa: F401
        return True
    except ImportError:
        return False


if __name__ == "__main__":
    pd.set_option("display.width", 160)
    main()
